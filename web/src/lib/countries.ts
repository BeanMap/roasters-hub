export function getCountryName(code: string, locale: string): string {
  const c = COUNTRIES.find((x) => x.code === code);
  if (!c) return code;
  if (locale === "pl") return c.pl;
  if (locale === "de") return c.de;
  return c.en;
}

export function searchCountries(query: string, _locale: string): Country[] {
  const q = query.toLowerCase().trim();
  if (!q) return COUNTRIES.slice(0, 10);
  return COUNTRIES.filter(
    (c) =>
      c.en.toLowerCase().includes(q) ||
      c.pl.toLowerCase().includes(q) ||
      c.de.toLowerCase().includes(q) ||
      c.code.toLowerCase() === q,
  ).slice(0, 15);
}
